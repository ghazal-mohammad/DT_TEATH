// سجلّ مركزي لمسح كواش الجلسة (in-memory SWR caches) عند تسجيل الخروج.
//
// المشكلة الأمنية: المستودعات مُسجَّلة كـ lazySingleton فتبقى حيّة طوال عمر
// التطبيق، وكواشها (SWR) تحمل بيانات المستخدم الحالي. بلا مسحها، يرى مستخدمٌ
// لاحق على نفس الجهاز بيانات المستخدم السابق للحظة قبل التحديث (تسريب بيانات).
//
// الحل: كل مستودع SWR يسجّل دالّة مسح كاشه هنا في مُنشئه، وتُستدعى جميعها في
// [AuthRepositoryImpl.logout]. مفكوك الارتباط: طبقة auth لا تعرف بقية المستودعات.
// ════════════════════════════════════════════════════════════════════════════

/// سجلّ عالمي (singleton) لدوال مسح كواش الجلسة.
class SessionCacheRegistry {
  SessionCacheRegistry._();

  /// النسخة الوحيدة.
  static final SessionCacheRegistry instance = SessionCacheRegistry._();

  final List<void Function()> _clearers = <void Function()>[];

  /// يسجّل دالّة مسح كاش (يستدعيها كل مستودع SWR في مُنشئه).
  void register(void Function() clear) => _clearers.add(clear);

  /// يمسح كل الكواش المُسجَّلة — يُستدعى عند تسجيل الخروج. فشل أي دالّة لا يوقف
  /// البقية (المسح الأمني يجب أن يكتمل مهما حدث).
  void clearAll() {
    for (final clear in _clearers) {
      try {
        clear();
      } catch (_) {
        // تجاهل: مسح كاش لا يجوز أن يفشل تسجيل الخروج.
      }
    }
  }
}
